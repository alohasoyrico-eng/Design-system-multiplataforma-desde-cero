const {
  fs,
  path,
  root,
  requiredFoundationContracts,
  add,
  read,
} = require("./audit-context.js");

const contractsDir = path.join(root, "packages/content/content/foundation-contracts/foundations");

function checkFoundationContracts() {
  const requiredSections = [
    "Source content:",
    "## Purpose",
    "## Definition Of Ready",
    "## Roles",
    "## Product Examples",
    "## Token Dependencies",
    "## Primitive Dependencies",
    "## Component Dependencies",
    "## Agent Instructions",
    "## Reject If",
  ];

  for (const id of requiredFoundationContracts) {
    const file = path.join(contractsDir, `${id}.md`);
    if (!fs.existsSync(file)) {
      add("errors", file, 1, `Missing portable Markdown contract for foundation: ${id}.`);
      continue;
    }
    const markdown = read(file);
    if (!markdown.includes("Generated portable foundation contract for Design System.")) {
      add("errors", file, 1, `Foundation contract ${id} must be generated by npm run build:foundation-contracts.`);
    }
    if (!markdown.includes(`artifacts/foundations/${id}.json`)) {
      add("errors", file, 1, `Foundation contract ${id} must cite its source spec shard.`);
    }
    if (!markdown.includes("packages/content/content/foundation-copy.json")) {
      add("errors", file, 1, `Foundation contract ${id} must cite foundation-copy.json as source content.`);
    }
    for (const section of requiredSections) {
      if (!markdown.includes(section)) {
        add("errors", file, 1, `Foundation contract ${id} missing required section: ${section}.`);
      }
    }
  }
}

module.exports = { checkFoundationContracts };
