const {
  fs,
  path,
  root,
  requiredComponentContracts,
  add,
  read,
} = require("./audit-context.js");

const contractsDir = path.join(root, "packages/content/content/component-contracts/components");

function checkComponentContracts() {
  for (const id of requiredComponentContracts) {
    const file = path.join(contractsDir, `${id}.md`);
    const sourceDir = path.join(root, "packages/content/content/component-copy/components", id);
    if (!fs.existsSync(file)) {
      add("errors", file, 1, `Missing portable Markdown contract for component: ${id}.`);
      continue;
    }
    const markdown = read(file);
    for (const required of ["Source content:", "## Purpose", "## Definition Of Ready", "## Use When", "## Do Not Use Without Review", "## Foundations", "## Implementation Checklist", "## MIEL"]) {
      if (!markdown.includes(required)) {
        add("errors", file, 1, `Component contract ${id} missing required section: ${required}.`);
      }
    }
    for (const required of ["Foundations required:", "Primitive dependencies:", "Component dependencies:", "Token dependencies:", "Gaps or review gates:"]) {
      if (!markdown.includes(required)) {
        add("errors", file, 1, `Component contract ${id} Definition Of Ready missing required gate: ${required}.`);
      }
    }
    const hasTestsSource = fs.existsSync(path.join(sourceDir, "tests-rejection-rules.json")) || (
      fs.existsSync(path.join(sourceDir, "all.json")) && read(path.join(sourceDir, "all.json")).includes('"tests-rejection-rules"')
    );
    if (hasTestsSource && !markdown.includes("## Tests And Rejection Rules")) {
      add("errors", file, 1, `Component contract ${id} missing required section: ## Tests And Rejection Rules.`);
    }
    if (!markdown.includes("Generated portable agent contract for Design System.")) {
      add("errors", file, 1, `Component contract ${id} must be generated by npm run build:component-contracts.`);
    }
    if (!fs.existsSync(sourceDir)) {
      add("errors", file, 1, `Component contract ${id} points to missing component-copy source.`);
    }
  }
}

module.exports = { checkComponentContracts };
