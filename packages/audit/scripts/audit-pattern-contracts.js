const {
  fs,
  path,
  root,
  requiredPatternContracts,
  add,
  read,
  readJson,
} = require("./audit-context.js");

const contractsDir = path.join(root, "packages/content/content/pattern-contracts/patterns");
const sourceDir = path.join(root, "packages/content/content/pattern-copy/patterns");
const catalogDir = path.join(root, "packages/content/content/catalog");
const patternTabsFile = path.join(root, "apps/docs/pattern-contract-tabs.js");
const candidatePatternDemosFile = path.join(root, "apps/docs/pattern-candidate-demos.js");
const patternSearchSlotFile = path.join(root, "apps/docs/search-slot.js");
const notificationPanelSlotFile = path.join(root, "apps/docs/notification-panel-slot.js");
const docsIndexFile = path.join(root, "apps/docs/index.html");
const docsChromeFile = path.join(root, "apps/docs/docs-chrome.js");
const patternFocusedDesignFile = path.join(root, "apps/docs/pattern-focused-design.js");
const patternShellRenderersFile = path.join(root, "apps/docs/pattern-shell-renderers.js");
const avatarMenuSlotFile = path.join(root, "apps/docs/avatar-menu-slot.js");
const mobilePatternDemosFile = path.join(root, "apps/docs/pattern-mobile-demos.js");
const desktopPatternDemosFile = path.join(root, "apps/docs/pattern-desktop-demos.js");
const utilityPatternDemosFile = path.join(root, "apps/docs/pattern-utility-demos.js");
const journeyPatternDemosFile = path.join(root, "apps/docs/pattern-journey-demos.js");

function checkPatternCatalogIds() {
  const ids = new Map();
  for (const catalogFile of fs.readdirSync(catalogDir).filter((file) => /^patterns-.*\.json$/.test(file)).sort()) {
    const file = path.join(catalogDir, catalogFile);
    const patterns = readJson(file).patterns ?? [];
    for (const pattern of patterns) {
      const seen = ids.get(pattern.id) ?? [];
      seen.push(file);
      ids.set(pattern.id, seen);
    }
  }
  for (const [id, files] of ids.entries()) {
    if (files.length > 1) {
      add("errors", files[1], 1, `Duplicate pattern id in catalog: ${id}.`);
    }
  }
}

function checkPatternContracts() {
  checkPatternCatalogIds();
  checkPatternDemoComposition();
  for (const id of requiredPatternContracts) {
    const file = path.join(contractsDir, `${id}.md`);
    const sourceFile = path.join(sourceDir, id, "all.json");
    if (!fs.existsSync(file)) {
      add("errors", file, 1, `Missing portable Markdown contract for pattern: ${id}.`);
      continue;
    }

    const markdown = read(file);
    for (const required of [
      "Source content:",
      "## Purpose",
      "## Use When",
      "## Do Not Use Without Review",
      "## Foundations",
      "## Slot Contract",
      "## Components And Primitives Used",
      "## Variants",
      "## Motion Contract",
      "## Accessibility",
      "## Implementation Checklist",
      "## Tests And Rejection Rules",
      "## MIEL",
    ]) {
      if (!markdown.includes(required)) {
        add("errors", file, 1, `Pattern contract ${id} missing required section: ${required}.`);
      }
    }

    if (!markdown.includes("Generated portable agent contract for Design System.")) {
      add("errors", file, 1, `Pattern contract ${id} must be generated by npm run build:pattern-contracts.`);
    }
    if (!markdown.includes(`packages/content/content/pattern-copy/patterns/${id}/all.json`) || !fs.existsSync(sourceFile)) {
      add("errors", file, 1, `Pattern contract ${id} points to missing pattern-copy source.`);
    }
    if (id === "sidebar" && /Collapsed rail.+\|\s*(Current|Candidate|Supported)/i.test(markdown)) {
      add("errors", file, 1, "Sidebar contract must not document collapsed rail as a supported variant.");
    }
    if (id === "sidebar" && !markdown.includes("drawer")) {
      add("errors", file, 1, "Sidebar contract must include drawer behavior.");
    }
    if (id === "topbar" && (!markdown.includes("notifications") || !markdown.includes("account"))) {
      add("errors", file, 1, "Topbar contract must include notifications and account slot coverage.");
    }
  }
}

function checkPatternDemoComposition() {
  if (!fs.existsSync(patternTabsFile)) return;
  checkPatternDemoLocalControls();
  checkSearchSlotSingleSource();
  const source = [patternTabsFile, candidatePatternDemosFile, mobilePatternDemosFile]
    .filter((file) => fs.existsSync(file))
    .map((file) => read(file))
    .join("\n");
  const requiredDemos = {
    "bulk-actions": {
      fn: "bulkActionsDemoPanel",
      components: ["button", "checkbox", "table", "dialog", "toast"],
    },
    "multi-step-form": {
      fn: "multiStepFormDemoPanel",
      components: ["stepper", "input", "button", "toast"],
    },
    settings: {
      fn: "settingsDemoPanel",
      components: ["switch", "select", "button", "dialog", "toast"],
    },
    "help-center": {
      fn: "helpCenterDemoPanel",
      components: ["input", "button", "card", "empty-state"],
    },
    "command-palette": {
      fn: "commandPaletteDemoPanel",
      components: ["dialog", "input", "menu", "button", "empty-state", "toast"],
    },
    "notification-panel": {
      fn: "notificationPanelDemoPanel",
      components: ["icon-button", "badge", "button", "list", "toast", "empty-state"],
    },
    "avatar-menu": {
      fn: "avatarMenuDemoPanel",
      components: ["menu", "avatar"],
    },
    "confirmation-dialog": {
      fn: "confirmationDialogDemoPanel",
      components: ["dialog", "button", "inline-validation", "toast"],
    },
    "action-sheet": {
      fn: "actionSheetDemoPanel",
      components: ["button", "menu", "toast"],
    },
    search: {
      fn: "searchDemoPanel",
      components: ["input", "select", "list", "empty-state", "inline-validation", "button"],
    },
    autocomplete: {
      fn: "autocompleteDemoPanel",
      components: ["combobox", "skeleton", "empty-state", "inline-validation"],
    },
    "select-option-layer": {
      fn: "selectOptionLayerDemoPanel",
      components: ["select", "card", "inline-validation", "button", "badge"],
    },
    "multi-select": {
      fn: "multiSelectDemoPanel",
      components: ["checkbox", "chip", "badge", "button", "inline-validation", "empty-state"],
    },
    "form-section": {
      fn: "formSectionDemoPanel",
      components: ["card", "input", "text-area", "inline-validation", "button", "toast"],
    },
    toolbar: {
      fn: "toolbarDemoPanel",
      components: ["input", "button", "menu", "badge", "chip", "toast"],
    },
    "filter-chip-group": {
      fn: "filterChipGroupDemoPanel",
      components: ["chip", "badge", "button", "empty-state", "toast"],
    },
    "file-upload": {
      fn: "fileUploadDemoPanel",
      components: ["button", "progress-indicator", "inline-validation", "tag", "empty-state", "toast"],
    },
    "fullscreen-sheet": {
      fn: "fullscreenSheetDemoPanel",
      components: ["stepper", "input", "button", "inline-validation", "card-summary", "toast"],
    },
    "swipe-actions": {
      fn: "swipeActionsDemoPanel",
      components: ["movement-row", "quick-action", "button", "toast"],
    },
    "quick-actions-grid": {
      fn: "quickActionsGridDemoPanel",
      components: ["quick-action", "tooltip", "dialog", "toast", "badge"],
    },
    "drawer-adapter": {
      fn: "drawerAdapterDemoPanel",
      components: ["drawer", "menu", "button", "dialog", "toast"],
    },
  };
  for (const [id, contract] of Object.entries(requiredDemos)) {
    const start = source.indexOf(`function ${contract.fn}()`);
    if (start === -1) {
      add("errors", patternTabsFile, 1, `Pattern ${id} must expose a real overview demo.`);
      continue;
    }
    const nextFunction = source.indexOf("\nfunction ", start + 1);
    const block = source.slice(start, nextFunction === -1 ? source.length : nextFunction);
    for (const component of contract.components) {
      const composed =
        block.includes(`packageDemo("${component}"`) ||
        (component === "input" && block.includes("searchSlotMarkup(") && fs.existsSync(patternSearchSlotFile) && read(patternSearchSlotFile).includes(`patternPackageDemo("input"`)) ||
        (id === "notification-panel" && block.includes("notificationPanelMarkup(") && fs.existsSync(notificationPanelSlotFile) && read(notificationPanelSlotFile).includes(`patternPackageDemo("${component}"`)) ||
        (id === "avatar-menu" && block.includes("avatarMenuMarkup(") && fs.existsSync(avatarMenuSlotFile) && (
          (component === "menu" && read(avatarMenuSlotFile).includes(`patternPackageDemo("menu"`)) ||
          (component === "avatar" && read(avatarMenuSlotFile).includes(`variant: "avatar-trigger"`))
        ));
      if (!composed) {
        add("errors", patternTabsFile, 1, `Pattern ${id} demo must compose Design System ${component} through packageDemo, not local markup.`);
      }
    }
    if (id === "select-option-layer" && /<article\s+data-select-layer-option|<strong>Standard policy|<span>Default card controls/.test(block)) {
      add("errors", candidatePatternDemosFile, 1, "Select Option Layer demo must not create local option cards; compose Design System Card/Badge/Button instead.");
    }
    if (id === "multi-select" && /<span\s+data-multi-select-count/.test(block)) {
      add("errors", candidatePatternDemosFile, 1, "Multi Select count must use a Design System status component, not loose text.");
    }
    if (["form-section", "toolbar", "filter-chip-group", "file-upload"].includes(id) && /<(button|input|select|textarea)\b(?![^>]*data-pattern-component)/.test(block)) {
      add("errors", candidatePatternDemosFile, 1, `Pattern ${id} demo must not create local controls; compose Design System controls through packageDemo.`);
    }
    if (id === "file-upload" && /<progress\b|type="file"/.test(block)) {
      add("errors", candidatePatternDemosFile, 1, "File Upload demo must not use local file/progress controls in docs; compose Design System Button and Progress Indicator.");
    }
    if (["fullscreen-sheet", "swipe-actions", "quick-actions-grid", "drawer-adapter"].includes(id) && /<(button|input|select|textarea|progress)\b(?![^>]*data-pattern-component)/.test(block)) {
      add("errors", mobilePatternDemosFile, 1, `Pattern ${id} demo must not create local controls; compose Design System controls through packageDemo.`);
    }
    if (id === "swipe-actions" && /touchstart|pointermove|translateX/.test(block)) {
      add("errors", mobilePatternDemosFile, 1, "Swipe Actions demo must expose explicit controls and avoid custom gesture physics.");
    }
  }
}

function checkSearchSlotSingleSource() {
  for (const file of [docsIndexFile, docsChromeFile, patternFocusedDesignFile, candidatePatternDemosFile, patternShellRenderersFile].filter((item) => fs.existsSync(item))) {
    const source = read(file);
    if (/<div[^>]+class="[^"]*\b(top-search|search-slot)\b[^"]*"[\s\S]*?<input\b/i.test(source)) {
      add("errors", file, 1, "Search must use shared searchSlotMarkup; do not create local search-slot input markup.");
    }
  }
  if (fs.existsSync(docsChromeFile) && !read(docsChromeFile).includes("searchSlotMarkup")) {
    add("errors", docsChromeFile, 1, "Docs topbar search must be mounted from shared searchSlotMarkup.");
  }
  if (fs.existsSync(patternFocusedDesignFile)) {
    const focusedSource = read(patternFocusedDesignFile);
    for (const helper of ["searchSlotMarkup", "notificationPanelMarkup", "avatarMenuMarkup"]) {
      if (!focusedSource.includes(helper)) add("errors", patternFocusedDesignFile, 1, `Topbar focused demos must consume shared ${helper}.`);
    }
    if (!focusedSource.includes('actionVariant: "account"') || !focusedSource.includes('navVariant: "sections"')) {
      add("errors", patternFocusedDesignFile, 1, "Topbar focused demos must cover sections plus account/notification slots.");
    }
  }
}

function checkPatternDemoLocalControls() {
  for (const file of [
    patternTabsFile,
    candidatePatternDemosFile,
    desktopPatternDemosFile,
    mobilePatternDemosFile,
    utilityPatternDemosFile,
    journeyPatternDemosFile,
  ].filter((item) => fs.existsSync(item))) {
    const source = read(file);
    const rawControl = /<(button|input|select|textarea|progress)\b/i.exec(source);
    if (rawControl) {
      add("errors", file, 1, `Pattern demos must not create local <${rawControl[1].toLowerCase()}> controls; compose Package components through packageDemo or use a documented shell pattern exception.`);
    }
  }
  if (fs.existsSync(patternShellRenderersFile) && read(patternShellRenderersFile).includes("pattern-account-menu")) {
    add("errors", patternShellRenderersFile, 1, "Shell pattern renderers must not create a parallel account menu; use avatarMenuMarkup.");
  }
}

module.exports = { checkPatternContracts };
