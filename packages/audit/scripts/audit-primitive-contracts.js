const {
  fs,
  path,
  root,
  requiredPrimitiveContracts,
  add,
  read,
} = require("./audit-context.js");

const contractsDir = path.join(root, "packages/content/content/primitive-contracts/primitives");

function checkPrimitiveContracts() {
  const requiredSections = [
    "Source content:",
    "## Purpose",
    "## Definition Of Ready",
    "## Roles",
    "## Product Examples",
    "## API",
    "## States",
    "## Responsibilities",
    "## Token Dependencies",
    "## Agent Instructions",
    "## Reject If",
  ];

  for (const id of requiredPrimitiveContracts) {
    const file = path.join(contractsDir, `${id}.md`);
    if (!fs.existsSync(file)) {
      add("errors", file, 1, `Missing portable Markdown contract for primitive: ${id}.`);
      continue;
    }
    const markdown = read(file);
    if (!markdown.includes("Generated portable primitive contract for Design System.")) {
      add("errors", file, 1, `Primitive contract ${id} must be generated by npm run build:primitive-contracts.`);
    }
    if (!markdown.includes(`artifacts/primitives/${id}.json`)) {
      add("errors", file, 1, `Primitive contract ${id} must cite its source spec shard.`);
    }
    if (!markdown.includes("packages/content/content/primitive-copy.json")) {
      add("errors", file, 1, `Primitive contract ${id} must cite primitive-copy.json as source content.`);
    }
    for (const section of requiredSections) {
      if (!markdown.includes(section)) {
        add("errors", file, 1, `Primitive contract ${id} missing required section: ${section}.`);
      }
    }
  }
}

module.exports = { checkPrimitiveContracts };
